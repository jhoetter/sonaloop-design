/**
 * gen-website-css.mjs — compile the docs-site "Website" section stylesheet.
 *
 * The Website section documents the shared marketing blocks (sonaloop-design/website). The docs
 * site is a dependency-free vanilla SPA, so we precompile the Tailwind utilities those blocks use
 * into a single committed stylesheet (no runtime Tailwind CDN).
 *
 * Scan  : src/website.tsx (the real components — source of the class names), the preview harness,
 *         the generated previews + site/app.js.
 * Config: shared tailwind-preset.js (colours/fonts/radii → CSS vars from styles/tokens.css),
 *         darkMode wired to [data-theme="dark"], preflight OFF so it can't clobber the .ds-* chrome.
 * Output: site/website.css = Tailwind utilities + the shared marketing utilities
 *         (styles/website.css, appended so the docs and the site share one source).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';
import tailwindcss from 'tailwindcss';
import preset from '../tailwind-preset.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const outPath = path.join(root, 'site/website.css');

const config = {
  presets: [preset],
  darkMode: ['selector', '[data-theme="dark"]'],
  corePlugins: { preflight: false },
  content: [
    path.join(root, 'src/website.tsx'),
    path.join(root, 'scripts/website-previews.harness.tsx'),
    path.join(root, 'site/website.previews.mjs'),
    path.join(root, 'site/app.js'),
  ],
  theme: { extend: {} },
};

const input = '@tailwind utilities;\n';
const result = await postcss([tailwindcss(config)]).process(input, { from: undefined });

// Append the shared marketing layout utilities (the single source the website also imports).
const marketing = fs.readFileSync(path.join(root, 'styles/website.css'), 'utf8');

const header = '/* GENERATED by scripts/gen-website-css.mjs — Tailwind utilities (from src/website.tsx)\n'
  + '   + styles/website.css. Do not edit; run `npm run gen`. */\n';
fs.writeFileSync(outPath, header + result.css + '\n' + marketing);
console.log('site/website.css written (%d bytes)', header.length + result.css.length + marketing.length + 1);
