/**
 * gen-website-previews.mjs — render the docs-site "Website" previews from the REAL components.
 *
 * The Website section documents the shared marketing blocks (sonaloop-design/website). To keep
 * the docs previews faithful (no mockups) and drift-free, we server-render the actual components
 * with realistic demo props (scripts/website-previews.harness.tsx) and write the resulting HTML
 * to the committed site/website.previews.mjs. The vanilla docs site (site/app.js) drops that HTML
 * straight into each preview stage.
 *
 * Build: esbuild bundles the harness (TSX + React + react-dom/server) to a single ESM module we
 * import in-process and call `renderAll()`. The components import brand canvases from `./images`
 * (which pull bundler-resolved .jpg assets) — in this Node SSR context we swap that module for a
 * shim returning the docs server's served URLs (/images/canvas/*.jpg, resolved from the repo root).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import esbuild from 'esbuild';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const outPath = path.join(root, 'site/website.previews.mjs');
// The harness is bundled to a temp file UNDER the repo (not a data: URL) so the externalized
// bare specifiers — react, react-dom/server, react/jsx-runtime — resolve against node_modules.
const tmpPath = path.join(root, 'site/.website-previews.build.mjs');

// Served-URL stand-in for sonaloop-design/images (the .jpg files live at images/canvas/*, which
// the docs server exposes from the repo root). Keeps real brand canvases in the previews without
// embedding megabytes of data-URIs.
const imagesShim = `
const pair = (name, light, dark) => ({ name, label: name, description: '', light, dark, width: 1800, height: 1200 });
export const canvas = pair('canvas', '/images/canvas/dawn.jpg', '/images/canvas/dusk.jpg');
export const abstract = pair('abstract', '/images/canvas/abstract-light.jpg', '/images/canvas/abstract-dark.jpg');
export const mist = pair('mist', '/images/canvas/mist-light.jpg', '/images/canvas/mist-dark.jpg');
export const meadow = pair('meadow', '/images/canvas/meadow-light.jpg', '/images/canvas/meadow-dark.jpg');
export const sky = pair('sky', '/images/canvas/sky-light.jpg', '/images/canvas/sky-dark.jpg');
export const canvases = { canvas, abstract, mist, meadow, sky };
export const canvasDawn = canvas.light;
export const canvasDusk = canvas.dark;
`;

const imagesShimPlugin = {
  name: 'images-shim',
  setup(build) {
    build.onResolve({ filter: /^\.\/images$/ }, () => ({ path: 'images-shim', namespace: 'images-shim' }));
    build.onLoad({ filter: /.*/, namespace: 'images-shim' }, () => ({ contents: imagesShim, loader: 'js' }));
  },
};

await esbuild.build({
  entryPoints: [path.join(root, 'scripts/website-previews.harness.tsx')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  jsx: 'automatic',
  // Keep node_modules (react, react-dom/server, react/jsx-runtime) external so Node resolves
  // them natively at import time — bundling react-dom/server pulls in `require('util')`, which
  // breaks under ESM. We only bundle our own src (+ the images shim).
  packages: 'external',
  outfile: tmpPath,
  logLevel: 'warning',
  plugins: [imagesShimPlugin],
});

let previews;
try {
  const mod = await import(pathToFileURL(tmpPath).href);
  previews = mod.renderAll();
} finally {
  fs.rmSync(tmpPath, { force: true });
}

const header = '/* GENERATED by scripts/gen-website-previews.mjs — server-rendered from the real\n'
  + '   sonaloop-design/website components (props in scripts/website-previews.harness.tsx). Each block is\n'
  + '   { controls, variants (combination-key -> HTML), defaultKey } — the docs control bar swaps variants. */\n';
fs.writeFileSync(outPath, `${header}export const blocks = ${JSON.stringify(previews, null, 1)};\n`);
const variants = Object.values(previews).reduce((n, b) => n + (b.examples ? b.examples.length : Object.keys(b.variants).length), 0);
console.log('site/website.previews.mjs written (%d blocks, %d variants)', Object.keys(previews).length, variants);
